func TestNsfwThresholdReport(t *testing.T) {
	t.Run("Configured", func(t *testing.T) {
		assert.Equal(t, "60", nsfwThresholdReport(true, 60, vision.NewNsfwModel(nsfw.ModelYahoo)))
	})
	t.Run("NoDetector", func(t *testing.T) {
		assert.Equal(t, "auto", nsfwThresholdReport(false, vision.DefaultNSFWThreshold, nil))
	})
	t.Run("Calibrated", func(t *testing.T) {
		assert.Equal(t, "auto (32.7)", nsfwThresholdReport(false, vision.DefaultNSFWThreshold, vision.NewNsfwModel(nsfw.ModelYahoo)))
		assert.Equal(t, "auto (52.9)", nsfwThresholdReport(false, vision.DefaultNSFWThreshold, &vision.Model{Type: vision.ModelTypeNsfw, Name: string(nsfw.ModelFalconsai)}))
	})
	t.Run("Remote", func(t *testing.T) {
		assert.Equal(t, "auto (75)", nsfwThresholdReport(false, vision.DefaultNSFWThreshold, newRemoteVisionModel(vision.ModelTypeNsfw, vision.RunAuto)))
	})
	t.Run("Custom", func(t *testing.T) {
		assert.Equal(t, "auto (80)", nsfwThresholdReport(false, vision.DefaultNSFWThreshold, &vision.Model{Type: vision.ModelTypeNsfw, Name: "custom", DefaultThreshold: 0.8}))
		assert.Equal(t, "auto (98)", nsfwThresholdReport(false, vision.DefaultNSFWThreshold, &vision.Model{Type: vision.ModelTypeNsfw, Name: "custom", DefaultThreshold: 75}))
	})
}
