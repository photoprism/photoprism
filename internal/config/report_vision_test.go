func TestVisionRunPhrase(t *testing.T) {
	cases := []struct {
		name  string
		model *vision.Model
		want  string
	}{
		{"Always", &vision.Model{Type: vision.ModelTypeLabels, Run: vision.RunAlways}, "in every context"},
		{"DefaultLabels", vision.NewLabelModel(classify.DefaultModelName()), "during indexing"},
		{"OnIndex", newRemoteVisionModel(vision.ModelTypeLabels, vision.RunOnIndex), "during indexing"},
		{"Manual", newRemoteVisionModel(vision.ModelTypeCaption, vision.RunManual), "only when requested"},
		{"OnSchedule", newRemoteVisionModel(vision.ModelTypeLabels, vision.RunOnSchedule), "on schedule"},
		{"OnDemand", newRemoteVisionModel(vision.ModelTypeLabels, vision.RunOnDemand), "after indexing and on schedule"},
		{"NewlyIndexed", newRemoteVisionModel(vision.ModelTypeLabels, vision.RunNewlyIndexed), "after indexing"},
		{"RemoteAuto", newRemoteVisionModel(vision.ModelTypeLabels, vision.RunAuto), "after indexing and on schedule"},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			assert.Equal(t, tc.want, visionRunPhrase(tc.model))
		})
	}
}

func TestVisionModelMissing(t *testing.T) {
	modelsPath := t.TempDir()
	t.Run("RegisteredMissing", func(t *testing.T) {
		assert.True(t, visionModelMissing(vision.NewLabelModel(classify.DefaultModelName()), modelsPath))
		assert.True(t, visionModelMissing(vision.NewNsfwModel(nsfw.ModelYahoo), modelsPath))
	})
	t.Run("RegisteredInstalled", func(t *testing.T) {
		installVisionTestArtifact(t, modelsPath, string(nsfw.ModelYahoo), nsfw.FindModel(nsfw.ModelYahoo).ONNX.File)
		assert.False(t, visionModelMissing(vision.NewNsfwModel(nsfw.ModelYahoo), modelsPath))
	})
	t.Run("Custom", func(t *testing.T) {
		assert.False(t, visionModelMissing(&vision.Model{Type: vision.ModelTypeLabels, Name: "custom_21k"}, modelsPath))
	})
	t.Run("Remote", func(t *testing.T) {
		assert.False(t, visionModelMissing(newRemoteVisionModel(vision.ModelTypeLabels, vision.RunAuto), modelsPath))
	})
	t.Run("Caption", func(t *testing.T) {
		assert.False(t, visionModelMissing(&vision.Model{Type: vision.ModelTypeCaption, Name: "caption"}, modelsPath))
	})
}

