// newVisionReportConfig returns a config with the default label and NSFW models installed in a
// temporary models path, applied to the vision configuration passed.
func newVisionReportConfig(t *testing.T, models *vision.ConfigValues) *Config {
	t.Helper()

	withVisionConfig(t, models)

	c := NewConfig(CliTestContext())
	c.options.ModelsPath = t.TempDir()
	c.options.OnnxProvider = "cpu"
	c.options.LabelsModel = "auto"
	c.options.NsfwModel = "auto"
	c.options.DetectNSFW = true
	c.options.UploadNSFW = false

	installVisionTestArtifact(t, c.ModelsPath(), string(classify.DefaultModelName()), classify.DefaultModel().ONNX.File)
	installVisionTestArtifact(t, c.ModelsPath(), string(nsfw.ModelYahoo), nsfw.FindModel(nsfw.ModelYahoo).ONNX.File)

	c.applyLabelModel()
	c.applyNSFWModel()

	return c
}

// newRemoteVisionModel returns a model of the specified type served by Ollama.
func newRemoteVisionModel(modelType vision.ModelType, run vision.RunType) *vision.Model {
	model := &vision.Model{Type: modelType, Engine: "ollama", Name: "qwen3-vl:4b-instruct", Run: run}
	model.ApplyEngineDefaults()
	return model
}

func TestConfig_VisionStatus(t *testing.T) {
	t.Run("Default", func(t *testing.T) {
		c := newVisionReportConfig(t, vision.NewConfig())
		lines := c.VisionStatus()
		require.Len(t, lines, 3+len(c.visionFacesStatus()))
		assert.Equal(t, "Labels are generated by efficientformerv2_s2 on the cpu provider during indexing.", lines[0])
		assert.Equal(t, "NSFW content is flagged by yahoo_open_nsfw on the cpu provider during indexing, and uploads are screened.", lines[1])
		assert.Equal(t, c.FaceStatus()[0], lines[2])
		assert.Contains(t, lines[len(lines)-1], "Captions are generated by ")
		assert.Contains(t, lines[len(lines)-1], " only when requested.")
	})
	t.Run("Nil", func(t *testing.T) {
		var c *Config
		assert.Equal(t, []string{"Computer vision is unavailable."}, c.VisionStatus())
		assert.Nil(t, c.VisionReportSections())
	})
}

func TestConfig_VisionReportSections(t *testing.T) {
	t.Run("Default", func(t *testing.T) {
		c := newVisionReportConfig(t, vision.NewConfig())
		sections := c.VisionReportSections()
		require.Len(t, sections, 3)
		assert.Equal(t, "Global Options", sections[0].Title)
		assert.Contains(t, sections[0].Rows, []string{"onnx-provider", "cpu"})
		assert.Equal(t, "Labels", sections[1].Title)
		assert.Contains(t, sections[1].Rows, []string{"labels-model", "auto (efficientformerv2_s2)"})
		assert.NotContains(t, sections[1].Rows, []string{"disable-classification", "true"})
		assert.Equal(t, "NSFW Detection", sections[2].Title)
		assert.Contains(t, sections[2].Rows, []string{"nsfw-model", "auto (yahoo_open_nsfw)"})
		assert.Contains(t, sections[2].Rows, []string{"upload-nsfw", "false"})
		assert.Contains(t, sections[2].Rows, []string{"Thresholds.NSFWIndex", "auto (32.7)"})
		assert.Contains(t, sections[2].Rows, []string{"Thresholds.NSFW", "75"})
	})
	t.Run("DeprecatedDisableClassification", func(t *testing.T) {
		c := newVisionReportConfig(t, vision.NewConfig())
		c.options.LabelsModel = ""
		c.options.DisableClassification = true
		rows := c.VisionReportSections()[1].Rows
		assert.Contains(t, rows, []string{"labels-model", "none"})
		assert.Contains(t, rows, []string{"disable-classification", "true"})
	})
	t.Run("DeprecatedIgnored", func(t *testing.T) {
		c := newVisionReportConfig(t, vision.NewConfig())
		c.options.DisableClassification = true
		assert.NotContains(t, c.VisionReportSections()[1].Rows, []string{"disable-classification", "true"})
	})
}

func TestConfig_visionLabelsStatus(t *testing.T) {
	t.Run("Disabled", func(t *testing.T) {
		c := newVisionReportConfig(t, vision.NewConfig())
		c.options.LabelsModel = "none"
		c.applyLabelModel()
		assert.Equal(t, "Image classification is disabled.", c.visionLabelsStatus())
	})
	t.Run("DisabledInVisionYaml", func(t *testing.T) {
		config := vision.NewConfig()
		config.Models[0].Disabled = true
		c := newVisionReportConfig(t, config)
		assert.Equal(t, "Image classification is disabled in the vision.yml file.", c.visionLabelsStatus())
	})
	t.Run("NoneInstalled", func(t *testing.T) {
		withVisionConfig(t, vision.NewConfig())
		c := NewConfig(CliTestContext())
		c.options.ModelsPath = t.TempDir()
		c.options.LabelsModel = "auto"
		c.applyLabelModel()
		assert.Equal(t, "Image classification is unavailable, because no label model is installed.", c.visionLabelsStatus())
	})
	t.Run("NamedNotInstalled", func(t *testing.T) {
		c := newVisionReportConfig(t, &vision.ConfigValues{Models: vision.Models{vision.NewLabelModel(classify.ModelRepViTM10)}})
		assert.Equal(t, "Labels are not generated, because repvit_m1_0 is not installed.", c.visionLabelsStatus())
	})
	t.Run("Never", func(t *testing.T) {
		config := vision.NewConfig()
		config.Models[0].Run = vision.RunNever
		c := newVisionReportConfig(t, config)
		assert.Equal(t, "Labels are not generated, because efficientformerv2_s2 on the cpu provider is configured to never run.", c.visionLabelsStatus())
	})
	t.Run("Remote", func(t *testing.T) {
		c := newVisionReportConfig(t, &vision.ConfigValues{Models: vision.Models{newRemoteVisionModel(vision.ModelTypeLabels, vision.RunOnSchedule)}})
		assert.Equal(t, "Labels are generated by qwen3-vl:4b-instruct through ollama on schedule.", c.visionLabelsStatus())
	})
}

func TestConfig_visionNsfwStatus(t *testing.T) {
	t.Run("None", func(t *testing.T) {
		c := newVisionReportConfig(t, vision.NewConfig())
		c.options.NsfwModel = "none"
		assert.Equal(t, "NSFW detection is disabled.", c.visionNsfwStatus())
	})
	t.Run("Labels", func(t *testing.T) {
		c := newVisionReportConfig(t, &vision.ConfigValues{Models: vision.Models{newRemoteVisionModel(vision.ModelTypeLabels, vision.RunAuto)}})
		c.options.NsfwModel = "labels"
		assert.Equal(t, "NSFW content is flagged based on the labels model response, and uploads are not screened in labels mode.", c.visionNsfwStatus())
		c.options.DetectNSFW = false
		assert.Equal(t, "NSFW content is not flagged, because detect-nsfw is off, and uploads are not screened in labels mode.", c.visionNsfwStatus())
	})
	t.Run("LabelsWithoutNSFWFields", func(t *testing.T) {
		c := newVisionReportConfig(t, vision.NewConfig())
		c.options.NsfwModel = "labels"
		assert.Equal(t, "NSFW content is not flagged, because the labels model cannot return NSFW fields, and uploads are not screened in labels mode.", c.visionNsfwStatus())
	})
	t.Run("DisabledInVisionYaml", func(t *testing.T) {
		config := vision.NewConfig()
		config.Models[1].Disabled = true
		c := newVisionReportConfig(t, config)
		assert.Equal(t, "NSFW detection is disabled in the vision.yml file.", c.visionNsfwStatus())
	})
	t.Run("NoneInstalled", func(t *testing.T) {
		withVisionConfig(t, vision.NewConfig())
		c := NewConfig(CliTestContext())
		c.options.ModelsPath = t.TempDir()
		c.options.NsfwModel = "auto"
		c.applyNSFWModel()
		assert.Equal(t, "NSFW detection is unavailable, because no detector is installed.", c.visionNsfwStatus())
	})
	t.Run("NamedNotInstalled", func(t *testing.T) {
		detector := vision.NewNsfwModel(nsfw.ModelFalconsai)
		detector.Default = false
		c := newVisionReportConfig(t, &vision.ConfigValues{Models: vision.Models{detector}})
		assert.Equal(t, "NSFW detection is unavailable, because falconsai_nsfw_image_detection_224 is not installed.", c.visionNsfwStatus())
	})
	t.Run("IndexOnly", func(t *testing.T) {
		c := newVisionReportConfig(t, vision.NewConfig())
		c.options.UploadNSFW = true
		assert.Equal(t, "NSFW content is flagged by yahoo_open_nsfw on the cpu provider during indexing, but uploads are not screened, because upload-nsfw is on.", c.visionNsfwStatus())
	})
	t.Run("UploadsOnly", func(t *testing.T) {
		c := newVisionReportConfig(t, vision.NewConfig())
		c.options.DetectNSFW = false
		assert.Equal(t, "Uploads are screened by yahoo_open_nsfw on the cpu provider, but indexed content is not flagged, because detect-nsfw is off.", c.visionNsfwStatus())
	})
	t.Run("NeverIsNotIndexing", func(t *testing.T) {
		config := vision.NewConfig()
		config.Models[1].Run = vision.RunNever
		c := newVisionReportConfig(t, config)
		assert.Equal(t, "Uploads are screened by yahoo_open_nsfw on the cpu provider, but indexed content is not flagged, because the detector is configured to never run.", c.visionNsfwStatus())
		c.options.UploadNSFW = true
		assert.Equal(t, "NSFW detection with yahoo_open_nsfw on the cpu provider is not used, because the detector is configured to never run and upload-nsfw is on.", c.visionNsfwStatus())
	})
	t.Run("Unused", func(t *testing.T) {
		c := newVisionReportConfig(t, vision.NewConfig())
		c.options.DetectNSFW = false
		c.options.UploadNSFW = true
		assert.Equal(t, "NSFW detection with yahoo_open_nsfw on the cpu provider is not used, because detect-nsfw is off and upload-nsfw is on.", c.visionNsfwStatus())
	})
	t.Run("Remote", func(t *testing.T) {
		c := newVisionReportConfig(t, &vision.ConfigValues{Models: vision.Models{newRemoteVisionModel(vision.ModelTypeNsfw, vision.RunAuto)}})
		assert.Equal(t, "NSFW content is flagged by qwen3-vl:4b-instruct through ollama after indexing and on schedule, and uploads are screened.", c.visionNsfwStatus())
	})
}

